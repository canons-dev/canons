// Content shipped in this package (canon/) and the managed-block / lock formats.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { Runner } from "./config.ts";
import { listMarkdown } from "./rules.ts";

// The modules run from src/ in development and from out/ when installed; both
// sit one level below the package root, and each holds its own canon/ copy
// (the build copies src/canon to out/canon).
export const CONTENT_ROOT = dirname(fileURLToPath(import.meta.url));
export const PACKAGE_ROOT = resolve(CONTENT_ROOT, "..");
/** Managed rules and skills live in this subdirectory of the consumer's rules and skills directories. */
export const MANAGED_SUBDIR = "canons";

export function sha256(text: string): string {
  return createHash("sha256").update(text).digest("hex");
}

/** Parsed JSON of `path`, or undefined when it is missing or not valid JSON. */
export function readJson(path: string): unknown {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return undefined;
  }
}

/** This package's own package.json. */
export function manifest(root = PACKAGE_ROOT): { name: string; version: string; repository?: { url?: string } } {
  return readJson(resolve(root, "package.json")) as { name: string; version: string };
}

export function packageVersion(root = PACKAGE_ROOT): string {
  return manifest(root).version;
}

export function packageName(root = PACKAGE_ROOT): string {
  return manifest(root).name;
}

/** The command the managed rules tell agents to run, per runner. */
export function runnerCommand(runner: Runner, root = PACKAGE_ROOT): string {
  return runner === "npx"
    ? `npx -y ${packageName(root)}@${packageVersion(root)}`
    : "npx canons";
}

export function availableLocales(root = CONTENT_ROOT): string[] {
  return readdirSync(resolve(root, "canon/core/locales"), {
    withFileTypes: true,
  })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

export interface Canon {
  version: string;
  locale: string;
  /** Body of the managed block, without markers. */
  block: string;
  /** Rule files keyed by their path below `.agents/rules/canons/`. */
  rules: Map<string, string>;
  /** Skill files keyed by their path below `.agents/skills/canons/`. */
  skills: Map<string, string>;
  /** Project settings and rules skeleton for a newly created AGENTS.md. */
  project: string;
}

/**
 * `root` is the directory holding `canon/` (src/ or out/). Shipped content
 * spells the command `npx canons`; other runners substitute their own.
 */
export function loadCanon(
  locale: string,
  root = CONTENT_ROOT,
  runner: Runner = "local",
): Canon {
  const command = runnerCommand(runner, resolve(root, ".."));
  const withRunner = (text: string) => text.replaceAll("`npx canons", `\`${command}`);
  const dir = resolve(root, "canon/core/locales", locale);
  if (!existsSync(dir))
    throw new Error(
      `locale "${locale}" is not shipped; available: ${availableLocales(root).join(", ")}`,
    );
  const load = (sub: string) => {
    const files = new Map<string, string>();
    const at = resolve(dir, sub);
    if (existsSync(at))
      for (const file of listMarkdown(at))
        files.set(file, withRunner(readFileSync(resolve(at, file), "utf8")));
    return files;
  };
  const rules = load("rules");
  const skills = load("skills");
  return {
    version: packageVersion(resolve(root, "..")),
    locale,
    block: withRunner(readFileSync(resolve(dir, "AGENTS.block.md"), "utf8").trim()),
    rules,
    skills,
    project: readFileSync(resolve(dir, "AGENTS.project.md"), "utf8"),
  };
}

// ---- managed block -------------------------------------------------------

const BEGIN_RE = /^<!-- canons:begin ([^\n]*?) -->$/m;
const END = "<!-- canons:end -->";

export function renderBlock(canon: Canon): string {
  return [
    `<!-- canons:begin version=${canon.version} locale=${canon.locale} sha256=${sha256(canon.block)} -->`,
    "<!-- Generated by canons. Do not edit inside this block: run `canons update`. Put project rules outside it. -->",
    "",
    canon.block,
    "",
    END,
  ].join("\n");
}

export interface BlockInfo {
  attrs: Record<string, string>;
  /** Body between the generated comment line and the end marker, trimmed. */
  body: string;
  start: number;
  end: number;
}

export function extractBlock(text: string): BlockInfo | undefined {
  const normalized = text.replace(/\r\n/g, "\n");
  const begins = normalized.match(new RegExp(BEGIN_RE.source, "gm")) ?? [];
  const ends = normalized.split(END).length - 1;
  if (!begins.length && !ends) return undefined;
  if (begins.length !== 1 || ends !== 1)
    throw new Error(
      "AGENTS.md must contain exactly one canons:begin / canons:end pair",
    );
  const m = BEGIN_RE.exec(normalized)!;
  const start = m.index;
  const endAt = normalized.indexOf(END, start);
  if (endAt < 0) throw new Error("canons:end appears before canons:begin");
  const attrs = Object.fromEntries(
    m[1]!
      .split(/\s+/)
      .filter(Boolean)
      .map((pair) => {
        const at = pair.indexOf("=");
        return [pair.slice(0, at), pair.slice(at + 1)];
      }),
  );
  const inner = normalized.slice(start + m[0].length, endAt).split("\n");
  // Drop the generated "Do not edit" comment line.
  const bodyLines = inner.filter(
    (line, i) => !(i <= 1 && line.startsWith("<!-- Generated by canons.")),
  );
  return {
    attrs,
    body: bodyLines.join("\n").trim(),
    start,
    end: endAt + END.length,
  };
}

/** Replaces the block in `text`, or inserts it at the top (after a leading H1, if any). */
export function upsertBlock(text: string, block: string): string {
  const normalized = text.replace(/\r\n/g, "\n");
  const info = extractBlock(normalized);
  if (info)
    return normalized.slice(0, info.start) + block + normalized.slice(info.end);
  const h1 = normalized.match(/^# [^\n]*\n/);
  if (h1)
    return `${h1[0]}\n${block}\n\n${normalized.slice(h1[0].length).replace(/^\n+/, "")}`;
  return `${block}\n\n${normalized.replace(/^\n+/, "")}`;
}

// ---- lock ----------------------------------------------------------------

export interface Lock {
  format: 1;
  canons: string;
  locale: string;
  /** sha256 of the managed block body. */
  digest: string;
  /** Repo-relative path of each managed file -> sha256 of its content. */
  hashes: Record<string, string>;
}

export function parseLock(text: string): Lock {
  let lock: Partial<Lock> | null | undefined;
  try {
    lock = JSON.parse(text) as Partial<Lock> | null;
  } catch {
    lock = undefined;
  }
  if (!lock || typeof lock !== "object" || lock.format !== 1 || !lock.hashes || typeof lock.hashes !== "object")
    throw new Error("canons.lock.json is not a valid canons lock file; restore it from git");
  return lock as Lock;
}

export function renderLock(lock: Lock): string {
  const hashes = Object.fromEntries(
    Object.entries(lock.hashes).sort(([a], [b]) => a.localeCompare(b)),
  );
  return `${JSON.stringify({ ...lock, hashes }, null, 2)}\n`;
}

/** True when going from `from` to `to` crosses a breaking boundary (major, or minor while 0.x). */
export function isBreakingUpgrade(from: string, to: string): boolean {
  const [fa = 0, fb = 0] = from.split(".").map(Number);
  const [ta = 0, tb = 0] = to.split(".").map(Number);
  if (ta !== fa) return ta > fa;
  return fa === 0 && tb > fb;
}
